export function localizeCategory(
  id: string,
  title: string,
  description: string,
  locale: Locale
): { title: string; description: string } {
  if (locale !== "uk") return { title, description };
  return {
    title: categoryTitlesUk[id] || title,
    description: categoryDescUk[id] || description,
  };
}

export function localizeDocumentMeta(
  slug: string,
  title: string,
  shortTitle: string,
  description: string,
  locale: Locale
): { title: string; shortTitle: string; description: string } {
  if (locale !== "uk") return { title, shortTitle, description };
  const uk = documentLocaleUk[slug];
  if (!uk) return { title, shortTitle, description };
  return uk;
}
