export function getDocumentBySlug(slug: string): LegalDocument | undefined {
  return documents.find((d) => d.slug === slug);
}


export function getDocumentsByCategory(category: string): LegalDocument[] {
  return documents.filter((d) => d.category === category);
}

export function searchDocuments(query: string): { doc: LegalDocument; article?: { number: string; title: string; content: string }; snippet: string }[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  const results: { doc: LegalDocument; article?: { number: string; title: string; content: string }; snippet: string }[] = [];

  for (const doc of documents) {
    if (
      doc.title.toLowerCase().includes(q) ||
      doc.shortTitle.toLowerCase().includes(q) ||
      doc.description.toLowerCase().includes(q) ||
      doc.tags.some((t) => t.includes(q))
    ) {
      results.push({ doc, snippet: doc.description.slice(0, 120) + "..." });
    }
    for (const section of doc.sections) {
      for (const art of section.articles || []) {
        if (
          art.number.toLowerCase().includes(q) ||
          art.title.toLowerCase().includes(q) ||
          art.content.toLowerCase().includes(q) ||
          (art.sanctions && art.sanctions.toLowerCase().includes(q))
        ) {
          results.push({
            doc,
            article: { number: art.number, title: art.title, content: art.content },
            snippet: `${art.number}. ${art.title}: ${art.content.slice(0, 80)}...`,
          });
        }
      }
    }
  }
  return results.slice(0, 50);
}
